#!/usr/bin/env node
/**
 * Generates src/curriculum/data.ts and docs/CURRICULUM.md from docs/curriculum.json (the course spec).
 *   node scripts/gen-curriculum.mjs [--stubs]
 * --stubs also creates a placeholder src/lectures/<id>-<slug>/index.tsx for lectures without a folder.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const spec = JSON.parse(readFileSync(join(root, 'docs/curriculum.json'), 'utf8'))
const withStubs = process.argv.includes('--stubs')

const slugify = (s) =>
  s
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/đ/g, 'd')
    .replace(/Đ/g, 'D')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')

const q = (s) => JSON.stringify(s ?? '')

// ---- modules ----
const modules = spec.modules.map((m, i) => ({
  id: m.id,
  label: `Modul ${i + 1}`,
  title: m.title,
  description: m.description,
  color: m.color,
}))

// ---- lectures ----
const lectures = spec.lectures.map((l) => ({
  id: l.id,
  slug: l.slug,
  module: l.module,
  title: l.title,
  subtitle: l.subtitle,
  durationMin: l.durationMin,
  prerequisites: l.prerequisites ?? [],
  objectives: l.objectives ?? [],
}))

// ---- glossary: id from the English term; lecture = first lecture listing the term ----
const termLecture = new Map()
for (const l of spec.lectures) {
  for (const t of l.glossaryTerms ?? []) {
    const k = slugify(t)
    if (!termLecture.has(k)) termLecture.set(k, l.id)
  }
}
const seen = new Set()
const glossary = []
for (const g of spec.glossary) {
  let id = slugify(g.term)
  if (seen.has(id)) id = `${id}-${glossary.length}`
  seen.add(id)
  glossary.push({ id, term: g.term, hr: g.hr, definition: g.definition, lecture: termLecture.get(id) ?? termLecture.get(slugify(g.hr)) })
}

const out = `// GENERATED by scripts/gen-curriculum.mjs from docs/curriculum.json — do not edit by hand.
import type { CourseModule, GlossaryEntry, LectureMeta } from './types'

export const COURSE = {
  title: ${q(spec.title)},
  tagline: ${q(spec.tagline)},
  /** When the facts in the lectures were last verified */
  verifiedAt: 'listopad 2026.',
}

export const MODULES: CourseModule[] = ${JSON.stringify(modules, null, 2)}

export const LECTURES: LectureMeta[] = ${JSON.stringify(lectures, null, 2)}

export const GLOSSARY: GlossaryEntry[] = ${JSON.stringify(
  glossary.map((g) => (g.lecture ? g : { id: g.id, term: g.term, hr: g.hr, definition: g.definition })),
  null,
  2,
)}
`
writeFileSync(join(root, 'src/curriculum/data.ts'), out)
console.log(`data.ts: ${modules.length} modules, ${lectures.length} lectures, ${glossary.length} glossary terms`)

// ---- docs/CURRICULUM.md ----
let md = `# ${spec.title}\n\n_${spec.tagline}_\n\n`
md += `Generated from [curriculum.json](curriculum.json). ${lectures.length} lectures in ${modules.length} modules, about ${Math.round(lectures.reduce((s, l) => s + l.durationMin, 0) / 60)} hours of self-paced study.\n\n`
md += `## Running example\n\n${spec.runningExample}\n\n`
for (const m of modules) {
  md += `## ${m.label}: ${m.title}\n\n${m.description}\n\n`
  for (const l of spec.lectures.filter((x) => x.module === m.id)) {
    md += `### ${l.id}. ${l.title}\n\n_${l.subtitle}_ · ~${l.durationMin} min${l.prerequisites?.length ? ` · nadovezuje se na ${l.prerequisites.join(', ')}` : ''}\n\n`
    md += `**Hook:** ${l.hook}\n\n`
    md += `**Ciljevi učenja:**\n${(l.objectives ?? []).map((o) => `- ${o}`).join('\n')}\n\n`
    md += `**Scene:**\n${(l.scenes ?? []).map((s, i) => `${i + 1}. **${s.title}** (${s.kind}): ${s.concept}`).join('\n')}\n\n`
    const f = l.flagshipSimulation
    if (f) md += `**Glavna simulacija: ${f.name}.** ${f.description}\n\n- _Pokvari:_ ${f.breakIt}\n- _Uvid:_ ${f.insight}\n\n`
    if (l.misconceptions?.length) md += `**Zablude koje razbijamo:**\n${l.misconceptions.map((x) => `- ${x}`).join('\n')}\n\n`
    if (l.codeArtifacts?.length) md += `**Kod:** ${l.codeArtifacts.map((c) => `${c.title} (${c.language})`).join(', ')}\n\n`
    md += `**Prijelaz dalje:** ${l.bridgeToNext}\n\n`
  }
}
md += `## Design rationale\n\n${spec.designRationale}\n`
writeFileSync(join(root, 'docs/CURRICULUM.md'), md)
console.log('docs/CURRICULUM.md written')

// ---- stubs ----
if (withStubs) {
  for (const l of lectures) {
    const dir = join(root, 'src/lectures', `${l.id}-${l.slug}`)
    const file = join(dir, 'index.tsx')
    if (existsSync(file)) continue
    mkdirSync(dir, { recursive: true })
    writeFileSync(
      file,
      `import { Callout, Section } from '../../kit'

// Placeholder — replaced when the lecture is written (see docs/AUTHORING.md).
export default function Lecture() {
  return (
    <Section id="uskoro" title="Predavanje u izradi">
      <Callout kind="info">Sadržaj ovog predavanja još se piše.</Callout>
    </Section>
  )
}
`,
    )
    console.log(`stub: ${dir}`)
  }
}
